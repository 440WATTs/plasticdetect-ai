// Looks up a translated field for a given plastic classId in the current
// language, falling back to the English value already computed by the
// caller (usually info.<field> from PLASTIC_DB) when no translation exists
// — e.g. for MIXED/UNKNOWN, which intentionally have no localized content.
function getLocalizedPlasticField(classId, field, fallback) {
  const lang = (typeof I18N !== "undefined") ? I18N.getLang() : "en";
  const langData = DATA_TRANSLATIONS[lang];
  if (langData && langData[classId] && langData[classId][field] !== undefined) {
    return langData[classId][field];
  }
  return fallback;
}

// Same idea for the "Not Plastic?" sheet's per-material note.
function getLocalizedNonPlasticNote(id, fallback) {
  const lang = (typeof I18N !== "undefined") ? I18N.getLang() : "en";
  const langData = DATA_TRANSLATIONS[lang];
  if (langData && langData.NON_PLASTIC && langData.NON_PLASTIC[id] !== undefined) {
    return langData.NON_PLASTIC[id];
  }
  return fallback;
}
